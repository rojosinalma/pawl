package scaffold

import (
	"bytes"
	"fmt"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/rojosinalma/pawl/internal/project"
)

// agentsFile is the agent instructions file; pawl owns one block in it.
const (
	agentsFile  = "AGENTS.md"
	agentsBegin = "<!-- BEGIN pawl (generated by pawl rules sync) -->"
	agentsEnd   = "<!-- END pawl -->"
)

type checklistItem struct {
	Title string
	Text  string
}

type agentsData struct {
	Checklist   []checklistItem
	NotEnforced []string
}

// writeAgents creates AGENTS.md, appends pawl's block to it, or replaces the block in place.
func writeAgents(p *project.Project, w *writer) error {
	existing, ok, err := w.read(agentsFile)
	if err != nil {
		return err
	}
	content, err := agentsContent(p, existing, ok)
	if err != nil {
		return err
	}
	switch {
	case !ok:
		return w.create(agentsFile, content, 0o644)
	case content == existing:
		w.res.Kept = append(w.res.Kept, agentsFile)
		return nil
	default:
		return w.overwrite(agentsFile, content, 0o644, true)
	}
}

// agentsContent returns AGENTS.md with pawl's block rendered from the manifest: a new file named after the
// directory, the block appended, or the block replaced in place.
func agentsContent(p *project.Project, existing string, exists bool) (string, error) {
	block, err := renderAgentsBlock(p)
	if err != nil {
		return "", err
	}
	if !exists {
		return "# " + filepath.Base(p.Root) + "\n\n" + block, nil
	}
	start := strings.Index(existing, agentsBegin)
	if start < 0 {
		if existing == "" {
			return block, nil
		}
		return withNewline(existing) + "\n" + block, nil
	}
	end := strings.Index(existing[start:], agentsEnd)
	if end < 0 {
		return "", fmt.Errorf("%s: %q has no matching %q; restore the end marker or delete the block", agentsFile, agentsBegin, agentsEnd)
	}
	end += start + len(agentsEnd)
	rest := strings.TrimPrefix(existing[end:], "\n")
	return existing[:start] + block + rest, nil
}

// renderAgentsBlock renders the marked block, ending with a newline.
func renderAgentsBlock(p *project.Project) (string, error) {
	t, err := template.ParseFS(templates, "templates/agents.md.tmpl")
	if err != nil {
		return "", fmt.Errorf("agents template: %w", err)
	}
	var b bytes.Buffer
	if err := t.Execute(&b, newAgentsData(p)); err != nil {
		return "", fmt.Errorf("render %s block: %w", agentsFile, err)
	}
	return b.String(), nil
}

// newAgentsData lists the review rules as the checklist and the waived or partly covered rules as not enforced.
func newAgentsData(p *project.Project) agentsData {
	var d agentsData
	for _, r := range p.Catalog.Rules {
		title := strings.TrimSuffix(oneLine(r.Title), ".")
		if r.IsReview() {
			d.Checklist = append(d.Checklist, checklistItem{Title: title, Text: oneLine(r.Guidance)})
			continue
		}
		e, ok := p.Manifest.Rules[r.ID]
		switch {
		case !ok:
			continue
		case e.Waived != "":
			d.NotEnforced = append(d.NotEnforced, title+": "+oneLine(e.Waived))
		case len(e.Gaps) > 0:
			d.NotEnforced = append(d.NotEnforced, title+" ("+oneLine(strings.Join(e.Gaps, "; "))+")")
		}
	}
	return d
}

// oneLine collapses whitespace so a text fits one Markdown list item.
func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}
